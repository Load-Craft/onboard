// Bundles each validator in validators/src into the single dependency-free file the skill ships:
// skills/<skill>/scripts/validate_<name>.mjs. Users run it with a bare `node`, no install step.
// The output must be reproducible byte for byte (`npm run check:skills` compares it with the
// committed copy), so there are no dates and no absolute paths in it.

import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(import.meta.dirname, '..', '..');
const { build } = createRequire(resolve(REPO, 'mcp', 'package.json'))('esbuild');

export const VALIDATORS = [
  { name: 'openapi', skill: 'loadcraft-openapi' },
  { name: 'asyncapi', skill: 'loadcraft-asyncapi' },
  { name: 'journeys', skill: 'loadcraft-journeys' },
  { name: 'overview', skill: 'loadcraft-overview' },
];

export function outputPath({ name, skill }) {
  return resolve(REPO, 'skills', skill, 'scripts', `validate_${name}.mjs`);
}

export async function buildTo(validator, outfile) {
  await build({
    absWorkingDir: REPO,
    entryPoints: [`validators/src/validate_${validator.name}.ts`],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'node',
    // The oldest Node the plugin supports (engines of mcp/package.json).
    target: 'node22',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    plugins: [
      {
        // The OpenAPI 3.0 type tree of @redocly/openapi-core needs one helper of ref-utils, whose
        // module would drag the whole library in; a small copy stands in for it.
        name: 'redocly-ref-utils-stub',
        setup(b) {
          b.onResolve({ filter: /(^|\/)ref-utils$/ }, (args) =>
            args.importer.includes('@redocly/openapi-core')
              ? { path: resolve(REPO, 'validators', 'src', 'ref-utils-stub.ts') }
              : undefined,
          );
        },
      },
    ],
    banner: {
      js: `#!/usr/bin/env node\n// LoadCraft ${validator.name} validator - generated by "npm run build:skills" from validators/src, do not edit.`,
    },
  });
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Optional names narrow the build (`node build.mjs journeys overview`).
  const only = process.argv.slice(2);
  for (const validator of VALIDATORS) {
    if (only.length === 0 || only.includes(validator.name)) {
      await buildTo(validator, outputPath(validator));
    }
  }
}
