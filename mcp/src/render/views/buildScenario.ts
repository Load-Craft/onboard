// View of `scenario_suggest_split` (the proposed traffic split as one bar per flow) and of
// `scenario_generate` (the generated scenarios and their composition: the same bars for the weights,
// the data mix and the self-check chain of every scenario, drawn by the renderer
// `scenario_check_self` shares).

import type { Translator } from '../../context.js';
import { bar, columns, decimal, inline, VIEW_WIDTH, wrap } from '../primitives.js';
import { needsInputScenarioLines, type NeedsInputView } from './needsInput.js';
import { oldDocsLines } from './oldDocs.js';
import {
  renderSelfCheckChain,
  renderSelfCheckHeader,
  type ScenarioCheck,
} from './selfCheckChain.js';

/** Where the split came from: the model's plan, an equal split because it gave none, or one flow. */
export type SplitSource = 'model' | 'equal_fallback' | 'single_flow';

export interface ProposalData {
  /** Name of the composition the split is for. */
  readonly name: string;
  readonly proposal: readonly { readonly flow: string; readonly percent: number }[];
  readonly source: SplitSource;
  /** Flows of the proposal pinned to an older docs version; absent when there is none. */
  readonly oldDocs?: readonly string[];
  /** Flows of the proposal the generator left open items on; absent when there is none. */
  readonly needsInput?: NeedsInputView;
}

/** Blocks of a full (100%) bar: 60% is 12 blocks. */
const BAR_WIDTH = 20;

export function renderBuildScenario(data: ProposalData, t: Translator): string {
  const rows = columns(
    data.proposal.map((row) => [
      inline(row.flow),
      `${String(row.percent).padStart(3)}%`,
      bar(row.percent / 100, BAR_WIDTH),
    ]),
  );
  const note =
    data.source === 'equal_fallback' ? wrap(t('buildScenario.equalFallback'), VIEW_WIDTH) : [];
  return [
    t('buildScenario.title'),
    ...rows,
    ...note,
    ...oldDocsLines(data.oldDocs ?? [], 0, 'scenario', t),
    ...needsInputScenarioLines(data.needsInput, t),
  ].join('\n');
}

// ---- phase 2: the generated scenarios and their composition ----------------------------------

/** What a share of the data mix is: typical data, invalid data, edge cases, or another type. */
export type DataRole = 'typical' | 'invalid' | 'edge';

export interface DataShare {
  /** Name of the test type as LoadCraft keys the mix (`happy_path` for typical data). */
  readonly type: string;
  readonly role: DataRole | null;
  /** How the project names the type; shown for a type without a role. */
  readonly label: string;
  readonly percent: number;
}

export interface GeneratedData {
  readonly name: string;
  /** The composition was created by this call, or it existed and got the new members and weights. */
  readonly composition: 'created' | 'updated';
  /** Scenarios in the composition. */
  readonly scenarios: number;
  /** Every scenario has compiled code (a scenario exists only when its generation compiled). */
  readonly compiled: boolean;
  readonly split: readonly { readonly flow: string; readonly percent: number }[];
  readonly dataMix: {
    readonly kind: 'normal' | 'realistic' | 'custom';
    readonly shares: readonly DataShare[];
  };
  readonly selfCheck: {
    /** The default environment the checks send their requests to; `null` when there is none. */
    readonly environment: string | null;
    readonly chains: readonly ScenarioCheck[];
  };
  /** At least one scenario was generated by this call. */
  readonly regenerated: boolean;
  /** Flows of the composition pinned to an older docs version; absent when there is none. */
  readonly oldDocs?: readonly string[];
  /** Flows of the composition the generator left open items on; absent when there is none. */
  readonly needsInput?: NeedsInputView;
}

/** Everything the two scenario tools return: the proposal of the split or the generated scenarios. */
export type BuildScenarioData = ProposalData | GeneratedData;

/** Where one generation of an operation handle ended (`process_wait` draws it). */
export type GenerationEnd =
  | { readonly status: 'completed'; readonly flow: string; readonly scenarioId: string }
  | { readonly status: 'failed'; readonly flow: string; readonly failure: GenerationFailure };

/** Why a scenario was not generated; `reason` is the backend's text, when it may be shown. */
export type GenerationFailure =
  | {
      readonly kind: 'error';
      readonly reason?: string;
      /** The backend says another try may succeed (a failure of the build infrastructure). */
      readonly recoverable: boolean;
      readonly retried: boolean;
      /**
       * The failure has the cause an earlier attempt of the same call failed with (the retry of this
       * flow, or an earlier flow): another try with the same input ends the same way.
       */
      readonly repeated?: boolean;
      /**
       * Tells the cause of one failure from another without keeping its text: a keyed digest of the
       * backend's text, valid in this server process only. Never shown.
       */
      readonly cause?: string;
    }
  | { readonly kind: 'cancelled' }
  | { readonly kind: 'not_produced' };

const NAME_LIMIT = 60;
const REASON_LIMIT = 200;
const STEP_LIMIT = 60;
function percentText(value: number, t: Translator): string {
  return Number.isInteger(value) ? String(value) : decimal(value, 1, t.locale);
}

function splitRows(split: GeneratedData['split'], t: Translator): string[] {
  return columns(
    split.map((row) => [
      inline(row.flow, NAME_LIMIT),
      `${percentText(row.percent, t).padStart(3)}%`,
      bar(row.percent / 100, BAR_WIDTH),
    ]),
  );
}

function headline(data: GeneratedData, t: Translator): string {
  const name = inline(data.name, NAME_LIMIT);
  if (data.composition === 'updated' && !data.regenerated) {
    return t('buildScenario.weightsOnly', { name });
  }
  const key = data.composition === 'created' ? 'buildScenario.created' : 'buildScenario.updated';
  const compiled = data.compiled ? t('buildScenario.compiled') : t('buildScenario.notCompiled');
  return `${t.plural(key, data.scenarios, { name })} · ${compiled}`;
}

function shareText(share: DataShare, t: Translator): string {
  const label =
    share.role === null ? inline(share.label, NAME_LIMIT) : t(`buildScenario.data.${share.role}`);
  return `${percentText(share.percent, t)}% ${label}`;
}

function dataLine(mix: GeneratedData['dataMix'], t: Translator): string[] {
  if (mix.kind === 'normal' || mix.shares.length === 0) return [];
  const shares = mix.shares.map((share) => shareText(share, t)).join(' · ');
  return wrap(t('buildScenario.dataMix', { shares }), VIEW_WIDTH);
}

/** The scenarios and the composition, the split, the data mix and the self-check of each scenario. */
export function renderGeneratedScenario(data: GeneratedData, t: Translator): string {
  const chains =
    data.selfCheck.chains.length === 0
      ? []
      : [
          renderSelfCheckHeader(data.selfCheck.environment, t),
          renderSelfCheckChain({ scenarios: data.selfCheck.chains }, t),
        ];
  return [
    headline(data, t),
    ...splitRows(data.split, t),
    ...dataLine(data.dataMix, t),
    ...chains,
    ...oldDocsLines(data.oldDocs ?? [], 0, 'scenario', t),
    ...needsInputScenarioLines(data.needsInput, t),
  ].join('\n');
}

/** The view of the tool: phase 1 or phase 2 by the shape of the data. */
export function renderBuildScenarioResult(data: BuildScenarioData, t: Translator): string {
  return 'proposal' in data ? renderBuildScenario(data, t) : renderGeneratedScenario(data, t);
}

/** Why one flow got no scenario, in one line. */
function failureText(failure: GenerationFailure, t: Translator): string {
  switch (failure.kind) {
    case 'error': {
      const reason =
        failure.reason === undefined
          ? t('buildScenario.failure.error')
          : inline(failure.reason, REASON_LIMIT);
      if (failure.retried) return t('buildScenario.failure.retried', { reason });
      return failure.repeated === true ? t('buildScenario.failure.repeated', { reason }) : reason;
    }
    case 'cancelled':
      return t('buildScenario.failure.cancelled');
    case 'not_produced':
      return t('buildScenario.failure.notProduced');
  }
}

/** The flows that failed with their reasons, one per line, for the error that lists them. */
export function renderGenerationFailures(
  failed: readonly { readonly flow: string; readonly failure: GenerationFailure }[],
  t: Translator,
): string {
  return failed
    .flatMap((item) =>
      wrap(`- ${inline(item.flow, NAME_LIMIT)}: ${failureText(item.failure, t)}`, VIEW_WIDTH, 2),
    )
    .join('\n');
}

/** Flow names for a sentence: `a, b, c`. */
export function renderFlowNames(flows: readonly string[]): string {
  return flows.map((flow) => inline(flow, NAME_LIMIT)).join(', ');
}

/** Where a generation stands, for the progress of the call. */
export function renderGenerationProgress(
  progress: {
    readonly flow: string;
    readonly index: number;
    readonly total: number;
    readonly step: string | null;
    readonly percent: number;
  },
  t: Translator,
): string {
  const params = {
    flow: inline(progress.flow, NAME_LIMIT),
    index: progress.index,
    total: progress.total,
  };
  return progress.step === null
    ? t('buildScenario.progress.start', params)
    : t('buildScenario.progress.step', {
        ...params,
        step: inline(progress.step, STEP_LIMIT),
        percent: Math.round(progress.percent),
      });
}

/** One generation followed by `process_wait`: done (the next call composes), or why it failed. */
export function renderGenerationEnd(end: GenerationEnd, t: Translator): string {
  const flow = inline(end.flow, NAME_LIMIT);
  return end.status === 'completed'
    ? t('buildScenario.generationDone', { flow })
    : t('buildScenario.generationFailed', { flow, reason: failureText(end.failure, t) });
}
