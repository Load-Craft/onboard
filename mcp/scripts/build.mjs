// Bundles src/server.ts into one dependency-free ESM file. The output must be reproducible byte for
// byte (no dates, no absolute paths), because `npm run check:dist` compares it with the committed copy.

import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const ROOT = resolve(import.meta.dirname, '..');
export const DEFAULT_OUT = resolve(ROOT, 'dist', 'server.mjs');
export const DEMO_BACKEND_OUT = resolve(ROOT, 'dist', 'demo-backend.mjs');

// CommonJS dependencies (`ws`) call require() for Node built-ins, which an ESM bundle does not have.
const REQUIRE_SHIM =
  "import { createRequire as __lcCreateRequire } from 'node:module';\n" +
  'const require = __lcCreateRequire(import.meta.url);';
// Optional native add-ons of `ws`; it falls back to JavaScript when they cannot be loaded.
const OPTIONAL_NATIVE = ['bufferutil', 'utf-8-validate'];

export async function buildTo(outfile, entry = 'src/server.ts') {
  const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
  await build({
    absWorkingDir: ROOT,
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    external: OPTIONAL_NATIVE,
    define: { __LOADCRAFT_VERSION__: JSON.stringify(pkg.version) },
    banner: {
      js: `// LoadCraft MCP server ${pkg.version} - generated by "npm run build" from mcp/src, do not edit.\n${REQUIRE_SHIM}`,
    },
  });
}

// The sample backend of the demonstration mode (`LOADCRAFT_DEMO=1`) is the fake backend of the tests
// on the world "sklep". It is built into a file of its own that the server imports only when the mode
// is on, so server.mjs holds none of it. The fake runs under a test runner, which it needs only for
// an end-of-test hook the demonstration never uses, and reads the contract files from disk; the
// bundle has to run without either, so both are replaced at build time.
const EMBEDDED_FILES = {
  'loadcraft-openapi.json': ['..', 'contracts', 'loadcraft-openapi.json'],
  'ws-frames.json': ['..', 'contracts', 'ws-frames.json'],
  'zakupy-run3-opis.json': ['test', 'fixtures', 'flows', 'zakupy-run3-opis.json'],
};

function demoBackendPlugins() {
  return [
    {
      name: 'demo-backend-no-test-runner',
      setup(b) {
        b.onResolve({ filter: /^vitest$/ }, () => ({ path: 'vitest', namespace: 'demo-stand-in' }));
        b.onLoad({ filter: /.*/, namespace: 'demo-stand-in' }, () => ({
          contents: 'export const onTestFinished = () => { throw new Error("no test runner"); };',
          loader: 'js',
        }));
      },
    },
    {
      // contract.ts, ws.ts and routes/describe.ts read their JSON through node:fs; they get the files as strings.
      name: 'demo-backend-embedded-contract',
      setup(b) {
        b.onResolve({ filter: /^node:fs$/ }, (args) =>
          /test[\\/]fake-backend[\\/](contract|ws|routes[\\\\/]describe)\.ts$/.test(args.importer)
            ? { path: 'node:fs', namespace: 'demo-embedded-fs' }
            : undefined,
        );
        b.onLoad({ filter: /.*/, namespace: 'demo-embedded-fs' }, () => {
          const files = Object.fromEntries(
            Object.entries(EMBEDDED_FILES).map(([name, parts]) => [
              name,
              JSON.stringify(
                JSON.stringify(JSON.parse(readFileSync(resolve(ROOT, ...parts), 'utf8'))),
              ),
            ]),
          );
          const table = `{${Object.entries(files)
            .map(([name, text]) => `${JSON.stringify(name)}: ${text}`)
            .join(',')}}`;
          return {
            contents:
              "import * as real from 'node:fs';\n" +
              `const embedded = ${table};\n` +
              'export function readFileSync(path, ...rest) {\n' +
              '  const name = String(path).split(/[\\\\/]/).pop();\n' +
              '  return Object.hasOwn(embedded, name) ? embedded[name] : real.readFileSync(path, ...rest);\n' +
              '}\n',
            loader: 'js',
            resolveDir: ROOT,
          };
        });
      },
    },
  ];
}

export async function buildDemoBackendTo(outfile) {
  const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
  await build({
    absWorkingDir: ROOT,
    entryPoints: ['test/fake-backend/demo.ts'],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    external: OPTIONAL_NATIVE,
    plugins: demoBackendPlugins(),
    define: { __LOADCRAFT_VERSION__: JSON.stringify(pkg.version) },
    banner: {
      js: `// LoadCraft sample backend for demonstration mode ${pkg.version} - generated by "npm run build" from mcp/test/fake-backend, do not edit.\n${REQUIRE_SHIM}`,
    },
  });
}

function option(argv, name) {
  const at = argv.indexOf(name);
  if (at === -1) return undefined;
  const value = argv[at + 1];
  if (value === undefined) throw new Error(`${name} needs a path`);
  return value;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const out = option(argv, '--out');
  await buildTo(out === undefined ? DEFAULT_OUT : resolve(out), option(argv, '--entry'));
  if (out === undefined && option(argv, '--entry') === undefined) {
    await buildDemoBackendTo(DEMO_BACKEND_OUT);
    // The default build also writes the tool list the skill tests read (dist/tools.json).
    const { TOOLS_OUT, renderTools } = await import('./list-tools.mjs');
    await writeFile(TOOLS_OUT, await renderTools(buildTo));
  }
}
