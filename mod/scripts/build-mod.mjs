// Bundles mod/src/register.ts (and what it imports from mod/src and mcp/src/render) into one ES
// module, mod/register.js, with the same bundler as mcp/dist/server.mjs. The output must be
// reproducible byte for byte, because `npm run check:mod` compares it with the committed copy.
//
// Claude Code analyses the built file statically (`claude plugin validate`), so the bundle must
// keep top-level functions and the literal event names: whitespace is minified, identifiers and
// syntax are not (the guards in mod/test read the built file by names and by statement shape).

import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(import.meta.dirname, '..', '..');
export const DEFAULT_OUT = resolve(REPO, 'mod', 'register.js');

// esbuild is a dev dependency of the server package; take that copy rather than adding one.
const { build } = createRequire(resolve(REPO, 'mcp', 'package.json'))('esbuild');

export async function buildModTo(outfile) {
  await build({
    absWorkingDir: REPO,
    entryPoints: ['mod/src/register.ts'],
    outfile,
    bundle: true,
    // Provided by Claude Code when it loads the module.
    external: ['claude-code'],
    format: 'esm',
    // A hooks module runs with no Node and no DOM: only standard JavaScript and web APIs.
    platform: 'neutral',
    target: 'es2023',
    sourcemap: false,
    minifyWhitespace: true,
    minifySyntax: false,
    minifyIdentifiers: false,
    keepNames: false,
    legalComments: 'none',
    logLevel: 'warning',
    banner: {
      js: '// LoadCraft mod - generated by "npm run build:mod" from mod/src, do not edit.',
    },
  });
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildModTo(DEFAULT_OUT);
}
