// Lint of the mod (src, test, tests, scripts): run `npm run lint` from mcp/, which calls ESLint in
// this folder. The packages come from mcp/node_modules (the mod has no package of its own).
import { createRequire } from 'node:module';

const fromMcp = createRequire(new URL('../mcp/package.json', import.meta.url));
const js = fromMcp('@eslint/js');
const tseslint = fromMcp('typescript-eslint');

const NODE_GLOBALS = { process: 'readonly', console: 'readonly', URL: 'readonly' };

// The rules the mod must keep everywhere: no `any`, no silencing the compiler or the linter.
const KEPT = {
  '@typescript-eslint/no-explicit-any': 'error',
  '@typescript-eslint/ban-ts-comment': [
    'error',
    { 'ts-expect-error': true, 'ts-ignore': true, 'ts-nocheck': true, 'ts-check': false },
  ],
  'no-console': 'error',
  'no-warning-comments': ['error', { terms: ['eslint-disable', 'noqa'], location: 'anywhere' }],
};

export default tseslint.config(
  // register.js is generated by `npm run build:mod`; types/ holds declarations only.
  { ignores: ['register.js', 'types/', 'node_modules/'] },
  {
    // The hooks module and its pure code: typed rules, from mod/tsconfig.json.
    files: ['src/**/*.ts', 'test/**/*.ts'],
    extends: [js.configs.recommended, ...tseslint.configs.recommendedTypeChecked],
    languageOptions: {
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname },
    },
    rules: {
      ...KEPT,
      '@typescript-eslint/no-floating-promises': 'error',
      '@typescript-eslint/no-unused-vars': ['error', { ignoreRestSiblings: true }],
    },
  },
  {
    // Tests that run under `claude plugin test` import `claude-code/testing`, whose declarations
    // exist only inside Claude Code, so the type-aware rules have nothing to read.
    files: ['tests/**/*.ts'],
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    rules: {
      ...KEPT,
      '@typescript-eslint/no-unused-vars': ['error', { ignoreRestSiblings: true }],
    },
  },
  {
    // Node scripts that build and test the mod.
    files: ['scripts/**/*.mjs', 'eslint.config.js'],
    extends: [js.configs.recommended],
    languageOptions: { globals: NODE_GLOBALS },
    rules: { 'no-console': KEPT['no-console'], 'no-warning-comments': KEPT['no-warning-comments'] },
  },
);
